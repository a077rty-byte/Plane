# 7. Encoder / decoder
# ==========================================================================
class Encoded:
    pass


def encode(img, algo, tau=1e-5, rule=RULE):
    """algo in {'standard', 'alg1', 'alg2'}"""
    t0 = time.perf_counter()
    n_img = img.shape[0]
    P = pool2(img)
    e = Encoded()
    e.algo, e.shape, e.maps, e.rmin = algo, img.shape, [], RMIN

    if algo == "standard":                                   # ---- standard fractal coding
        e.seed_mask = np.zeros(img.shape, bool)
        anchors = [(y, x) for y in range(0, n_img - 2 * STD_RANGE + 1, STD_STRIDE)
                   for x in range(0, n_img - 2 * STD_RANGE + 1, STD_STRIDE)]
        pool = DomainPool(P, anchors, STD_RANGE, n_img)
        e.pools, e.dom = {STD_RANGE: pool}, []
        for y in range(0, n_img, STD_RANGE):
            for x in range(0, n_img, STD_RANGE):
                d, k, si, o, _ = best_match(img[y:y + STD_RANGE, x:x + STD_RANGE].ravel(),
                                            pool, pool.candidates())
                e.maps.append((y, x, STD_RANGE, d, k, si, o))
        e.seed_bytes = 0
        e.bits = _count_bits(e, tree_bits=0)
        e.time = time.perf_counter() - t0
        return e

    # ---- proposed algorithms I and II
    import zlib
    leaves = quadtree(img, MAX_SIZE, DMIN, SPLIT_VAR)
    dom, rng_blocks, e.tau_eff = separate_domain_range(img, leaves, DMIN, tau, rule)
    e.leaves, e.dom = leaves, dom
    e.seed_mask = np.zeros(img.shape, bool)
    for (y, x, s) in dom:
        e.seed_mask[y:y + s, x:x + s] = True
    e.seed_bytes = len(zlib.compress(img[e.seed_mask].astype(np.uint8).tobytes(), 9))  # lossless part
    anchors = [(y, x) for (y, x, s) in dom]

    e.pools, r = {}, MAX_SIZE
    while r >= RMIN:
        e.pools[r] = DomainPool(P, anchors, r, n_img, use_som=(algo == "alg2"))
        r //= 2

    stack = list(rng_blocks)
    while stack:
        y, x, r = stack.pop()
        blk = img[y:y + r, x:x + r]
        pool = e.pools[r]
        lab = None
        if algo == "alg2":                                   # group label of the range block
            lab = int(pool.som.predict(block_features(blk[None]))[0])
        d, k, si, o, sse = best_match(blk.ravel(), pool, pool.candidates(lab))
        if math.sqrt(sse / (r * r)) > TOL and r > RMIN:      # poor match -> 4 smaller range blocks
            h = r // 2
            stack += [(y, x, h), (y, x + h, h), (y + h, x, h), (y + h, x + h, h)]
        else:
            e.maps.append((y, x, r, d, k, si, o))
    e.bits = _count_bits(e, tree_bits=len(leaves) * 4 // 3 + len(dom) // 8)
    e.time = time.perf_counter() - t0
    return e


def _count_bits(e, tree_bits):
    """Size of the compressed stream: IFS codes + tree + lossless seed blocks."""
    bits = tree_bits
    for (y, x, r, d, k, si, o) in e.maps:
        bits += math.ceil(math.log2(max(2, e.pools[r].n))) + ISO_BITS + S_BITS + O_BITS
        if e.algo != "standard" and r > e.rmin:
            bits += 1                                        # "split" flag
    return bits + 8 * e.seed_bytes


def compression_ratio(e):
    return e.shape[0] * e.shape[1] * 8.0 / e.bits


def decode(e, original=None, iters=DECODE_ITERS):
    """IFS decoding: iterate the maps from a flat grey image; the lossless seed blocks
    are written back at every iteration."""
    cur = np.full(e.shape, 128.0)
    use_seed = original is not None and e.seed_mask.any()
    if use_seed:
        cur[e.seed_mask] = original[e.seed_mask]
    for _ in range(iters):
        P = pool2(cur)
        new = cur.copy()
        for (y, x, r, d, k, si, o) in e.maps:
            py, px = e.pools[r].pos[d]
            new[y:y + r, x:x + r] = S_LEVELS[si] * isometry(P[py:py + 2 * r:2, px:px + 2 * r:2], k) + o
        cur = np.clip(new, 0, 255)
        if use_seed:
            cur[e.seed_mask] = original[e.seed_mask]
    return np.rint(cur)


def run(img, algo, tau=1e-5, rule=RULE, repeats=1):
    """encode + decode.  Time = mean encoding time over `repeats` runs."""
    times = []
    for _ in range(max(1, repeats)):
        e = encode(img, algo, tau, rule)
        times.append(e.time)
    rec = decode(e, img)
    return e, rec, psnr(img, rec), float(np.mean(times)), compression_ratio(e)


