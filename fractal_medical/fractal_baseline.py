"""
BASELINE  --  Fractal image coding of medical (MRI) images following
    S. Bhavani, K. Thanushkodi, "Neural based domain and range pool partitioning
    using Fractal Coding for nearly lossless Medical Image Compression",
    WSEAS Trans. on Signal Processing, 9(1), 2013.

This file is meant to be the REFERENCE for every later development:
no chaotic maps, no speed-ups, no extra metrics.  Only what the paper describes.

Algorithms (Section 3 of the paper)
  standard : fixed range blocks, all domain blocks, 8 isometries, full search.
  alg1     : quad-tree decomposition + variance based domain/range separation
             (threshold tau).  Domain blocks are kept LOSSLESSLY (seeds); the
             other blocks are generated by the IFS (fractal) code.
  alg2     : alg1 + Self-Organising-Map grouping.  A range block is matched only
             with the domain blocks of its own SOM group.

Data
  Reads the images straight from the ZIP archive (or from a folder), keeps ONE
  class (default: notumor) and N images (default: 5), converts them to 8-bit
  grey level and 512 x 512 (paper size).

Outputs (same layout as the paper)
  Table 1  PSNR at different thresholds          Fig. 1  partition + domain blocks (images 1, 2)
  Table 2  encoding time at different thresholds Fig. 2  domain blocks for several tau (images 3, 4)
  Table 3  compression ratio                     Fig. 3  performance analysis
  Table 4  the three algorithms, Sample image 4  Fig. 5-8 reconstruction + comparison charts

Run
  python fractal_baseline.py --source /content/drive/MyDrive/archive.zip
"""
