def list_images(source):
    """Return [(member_name, opener)] for every image of a .zip file or of a folder."""
    out = []
    if os.path.isfile(source) and source.lower().endswith(".zip"):
        z = zipfile.ZipFile(source)
        for n in sorted(z.namelist()):
            if n.lower().endswith(EXTS) and not n.endswith("/") and "__MACOSX" not in n:
                out.append((n, (lambda name=n: z.read(name))))
    elif os.path.isdir(source):
        for p in sorted(glob.glob(os.path.join(source, "**", "*"), recursive=True)):
            if p.lower().endswith(EXTS):
                rel = os.path.relpath(p, source).replace(os.sep, "/")
                out.append((rel, (lambda path=p: open(path, "rb").read())))
    else:
        raise SystemExit("--source must be a .zip file or a folder: %s" % source)
    return out


def select_images(source, cls, n, split, seed, manifest):
    """Choose n images of class `cls`.  The choice is deterministic and is written to
    `manifest`; if the manifest already exists it is re-used (same images in every run)."""
    items = dict(list_images(source))
    if manifest and os.path.exists(manifest):
        names = [l.strip() for l in open(manifest, encoding="utf-8") if l.strip()]
        missing = [m for m in names if m not in items]
        if missing:
            raise SystemExit("images of the manifest are not in the source: %s" % missing[:3])
        return names, items
    cand = [m for m in items if os.path.basename(os.path.dirname(m)).lower() == cls.lower()]
    if split:
        sp = [m for m in cand if ("/" + split.lower() + "/") in ("/" + m.lower())]
        cand = sp or cand
    if len(cand) < n:
        raise SystemExit("only %d images of class '%s' found (need %d)" % (len(cand), cls, n))
    names = sorted(random.Random(seed).sample(sorted(cand), n))
    return names, items


def load_image(data, size=IMG_SIZE):
    """bytes -> 8-bit grey level, size x size (bicubic resize when needed)."""
    from PIL import Image
    im = Image.open(io.BytesIO(data)).convert("L")
    if im.size != (size, size):
        im = im.resize((size, size), Image.BICUBIC)
    return np.asarray(im, dtype=np.float64)


# ==========================================================================
# 4. Quad-tree decomposition and domain / range separation (Section 3.1)
# ==========================================================================
def quadtree(img, max_size, min_size, split_var):
    """Variance driven quad-tree.  Returns the leaves (y, x, size)."""
    leaves = []

    def rec(y, x, s):
        blk = img[y:y + s, x:x + s]
        if s > min_size and (s > max_size or blk.var() > split_var):
            h = s // 2
            for dy in (0, h):
                for dx in (0, h):
                    rec(y + dy, x + dx, h)
        else:
            leaves.append((y, x, s))

    n = img.shape[0]
    for y in range(0, n, max_size):
        for x in range(0, n, max_size):
            rec(y, x, max_size)
    return leaves


def tau_effective(tau, rule=RULE):
    """
    The paper's separation rule (page 13):
        size(b) > d_min                          -> Range
        elif  var(b) >= tau * var_max            -> Domain  (feature rich)
        else                                     -> Range
    with var_max = maximum variance of the d_min x d_min blocks.

    rule = "literal": use tau exactly as printed.  With tau = 1e-3 ... 1e-6 almost
        EVERY d_min block becomes a domain block and tau has almost no effect.
    rule = "figure" (default): the paper's Fig. 2 shows the opposite behaviour
        (tau = 1e-3 keeps MORE domain blocks than tau = 1e-6).  To reproduce Fig. 2
        the ratio var/var_max is compared with
            tau_eff = 0.2 * (tau / 1e-6) ** (-1/3)
        i.e. 1e-3 -> 0.02, 1e-4 -> 0.043, 1e-5 -> 0.093, 1e-6 -> 0.2.
        (This mapping is OUR choice; the paper gives no formula.)
    """
    return tau if rule == "literal" else 0.2 * (tau / 1e-6) ** (-1.0 / 3.0)


def separate_domain_range(img, leaves, dmin, tau, rule=RULE):
    vmax = max(1e-9, max(img[y:y + s, x:x + s].var() for (y, x, s) in leaves if s == dmin))
    t_eff = tau_effective(tau, rule)
    dom, rng_ = [], []
    for (y, x, s) in leaves:
        if s == dmin and img[y:y + s, x:x + s].var() >= t_eff * vmax:
            dom.append((y, x, s))
        else:
            rng_.append((y, x, s))
    return dom, rng_, t_eff


# ==========================================================================
# 5. Self-Organising Map (Kohonen), Section 3.2
# ==========================================================================
class SOM:
    """
    1. randomise the weight vectors of the nodes   2. grab an input vector
    3. traverse every node   4. Euclidean distance between input and node weights
    5. the node with the smallest distance is the Best Matching Unit (BMU)
    6. update the neighbourhood of the BMU:
           Wv(t+1) = Wv(t) + theta(t) * alpha(t) * (D(t) - Wv(t))
    There is no activation function in a SOM: the winner is chosen by distance and
    theta(t) = exp(-d^2 / (2 sigma(t)^2)) is the (Gaussian) neighbourhood function.
    alpha(t) and sigma(t) decrease linearly.
    """

    def __init__(self, grid=SOM_GRID, epochs=SOM_EPOCHS, lr0=SOM_LR0, seed=SOM_SEED):
        self.grid, self.epochs, self.lr0 = grid, epochs, lr0
        self.rs = np.random.RandomState(seed)
        gy, gx = np.mgrid[0:grid[0], 0:grid[1]]
        self.pos = np.stack([gy.ravel(), gx.ravel()], 1).astype(float)
        self.n = grid[0] * grid[1]

    def fit(self, X):
        X = np.asarray(X, dtype=np.float64)
        idx = self.rs.choice(len(X), self.n, replace=len(X) < self.n)      # random initial weights
        self.W = X[idx].copy() + 1e-3 * self.rs.randn(self.n, X.shape[1])  # (= random training samples)
        total = self.epochs * len(X)
        t = 0
        sig0 = max(self.grid) / 2.0
        for _ in range(self.epochs):
            for i in self.rs.permutation(len(X)):
                f = 1.0 - t / total
                alpha, sig = self.lr0 * f, max(0.5, sig0 * f)
                d = ((self.W - X[i]) ** 2).sum(1)
                bmu = d.argmin()
                theta = np.exp(-((self.pos - self.pos[bmu]) ** 2).sum(1) / (2 * sig ** 2))
                self.W += (theta * alpha)[:, None] * (X[i] - self.W)
                t += 1
        return self

    def predict(self, X):
        X = np.asarray(X, dtype=np.float64)
        return ((X[:, None, :] - self.W[None]) ** 2).sum(2).argmin(1)


def block_features(blocks):
    """Feature vector of (N, r, r) blocks, invariant to the 8 isometries:
    mean, standard deviation and the sorted, normalised quadrant means."""
    n, r, _ = blocks.shape
    h = r // 2
    q = np.stack([blocks[:, :h, :h].mean((1, 2)), blocks[:, :h, h:].mean((1, 2)),
                  blocks[:, h:, :h].mean((1, 2)), blocks[:, h:, h:].mean((1, 2))], 1)
    mu = blocks.mean((1, 2))
    sd = blocks.std((1, 2))
    dev = np.sort(q - mu[:, None], 1) / (sd[:, None] + 1.0)
    return np.column_stack([mu / 255.0, np.minimum(sd, 64) / 64.0, 0.3 * dev])


# ==========================================================================
# 6. Fractal matching machinery (Section 2)
# ==========================================================================
class DomainPool:
    """Domain candidates for ONE range size r: windows 2r x 2r anchored at the domain
    (seed) blocks, down-sampled to r x r, each with its 8 isometries."""

    def __init__(self, P, anchors, r, n_img, use_som=False):
        pos = sorted({(min(y, n_img - 2 * r), min(x, n_img - 2 * r)) for (y, x) in anchors})
        self.pos = np.array(pos)
        base = np.stack([P[y:y + 2 * r:2, x:x + 2 * r:2] for (y, x) in pos])
        self.n, self.r = len(pos), r
        self.all = np.stack([isometry(base, k).reshape(self.n, -1)
                             for k in range(8)]).astype(np.float32)        # (8, N, r*r)
        self.sum_d = self.all[0].sum(1)
        self.sum_dd = (self.all[0] ** 2).sum(1)
        self.labels = None
        if use_som:
            self.som = SOM().fit(block_features(base))
            self.labels = self.som.predict(block_features(base))

    def candidates(self, label=None):
        """Indices of the domain windows that must be searched."""
        if label is None or self.labels is None:
            return np.arange(self.n)
        idx = np.where(self.labels == label)[0]
        if len(idx) == 0:                                    # empty group -> nearest non-empty one
            used = np.unique(self.labels)
            d = ((self.som.W[used] - self.som.W[label]) ** 2).sum(1)
            idx = np.where(self.labels == used[d.argmin()])[0]
        return idx


def best_match(rv, pool, idx):
    """Least-squares (s, o) for every candidate and isometry; returns the best
    (domain index, isometry, s index, o, squared error) for the range vector rv."""
    n = rv.size
    sr, srr = rv.sum(), (rv ** 2).sum()
    D = pool.all[:, idx, :]
    sd, sdd = pool.sum_d[idx], pool.sum_dd[idx]
    sdr = D @ rv.astype(np.float32)
    den = n * sdd - sd ** 2
    s = np.where(den > 1e-6, (n * sdr - sd * sr) / np.maximum(den, 1e-6), 0.0)
    si = np.abs(s[..., None] - S_LEVELS).argmin(-1)                     # quantise s
    sq = S_LEVELS[si]
    o = np.clip(np.rint((sr - sq * sd) / n), -256, 255)                 # quantise o
    sse = (sq ** 2 * sdd + n * o ** 2 + srr + 2 * sq * o * sd - 2 * sq * sdr - 2 * o * sr)
    k, m = np.unravel_index(sse.argmin(), sse.shape)
    return int(idx[m]), int(k), int(si[k, m]), int(o[k, m]), float(max(sse[k, m], 0))


