def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", required=True, help="archive.zip (or a folder) with the MRI images")
    ap.add_argument("--cls", default="notumor", help="class folder name (default: notumor)")
    ap.add_argument("--n", type=int, default=5, help="number of images (default 5)")
    ap.add_argument("--split", default="Training", help="use the Training/ or Testing/ part ('' = both)")
    ap.add_argument("--seed", type=int, default=1, help="seed of the (reproducible) image choice")
    ap.add_argument("--manifest", help="text file with the chosen image names; re-used if it exists")
    ap.add_argument("--size", type=int, default=IMG_SIZE, help="image side (paper: 512, multiple of 32)")
    ap.add_argument("--rule", choices=["figure", "literal"], default=RULE)
    ap.add_argument("--repeats", type=int, default=1, help="timing = mean of this many encodings")
    ap.add_argument("--t4-image", type=int, default=4, help="Sample image used in Table 4 (paper: 4)")
    ap.add_argument("--out", default="results_baseline")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)

    manifest = a.manifest or os.path.join(a.out, "selected_images.txt")
    names, items = select_images(a.source, a.cls, a.n, a.split, a.seed, manifest)
    for path in {manifest, os.path.join(a.out, "selected_images.txt")}:   # keep a copy next to the results
        with open(path, "w", encoding="utf-8") as f:
            f.write("\n".join(names) + "\n")
    images = [load_image(items[m](), a.size) for m in names]
    from PIL import Image
    for i, im in enumerate(images):
        Image.fromarray(im.astype(np.uint8)).save(os.path.join(a.out, "input_%d.png" % (i + 1)))
    t4_idx = min(max(a.t4_image, 1), len(images)) - 1
    mapping = ["Sample MRI Image %d = %s" % (i + 1, m) for i, m in enumerate(names)]
    settings = [
        "Settings: class=%s  images=%d  size=%dx%d  rule=%s  repeats=%d" % (a.cls, len(images), a.size, a.size, a.rule, a.repeats),
        "  quad-tree: max block %d, d_min %d, r_min %d, split variance %.0f, range RMS tolerance %.1f" % (MAX_SIZE, DMIN, RMIN, SPLIT_VAR, TOL),
        "  s: %d levels in [-0.95, 0.95]; bits: s=%d o=%d isometry=%d; seeds compressed with zlib" % (len(S_LEVELS), S_BITS, O_BITS, ISO_BITS),
        "  SOM: grid %dx%d, %d epochs, lr0 %.1f, random initial weights, linear schedules, seed %d" % (SOM_GRID[0], SOM_GRID[1], SOM_EPOCHS, SOM_LR0, SOM_SEED),
        "  tau_eff (var/var_max threshold): " + ", ".join("%s -> %.4f" % (tlabel(t), tau_effective(t, a.rule)) for t in TAU_LIST),
        "  standard coder: %dx%d ranges, 2x larger domains every %d px; decoder: %d iterations" % (STD_RANGE, STD_RANGE, STD_STRIDE, DECODE_ITERS),
        "  Table 4 image: Sample MRI Image %d" % (t4_idx + 1),
    ]
    print("\n".join(mapping + [""] + settings), flush=True)

    # ---- Tables 1-3: Algorithm II at the four thresholds
    enc = {}
    for i, im in enumerate(images):
        for t in TAU_LIST:
            e, rec, p, tm, cr = run(im, "alg2", t, a.rule, a.repeats)
            e.metrics = dict(psnr=p, time=tm, cr=cr)
            enc[(i, t)] = e
            print("  image %d  %s  PSNR=%6.2f  time=%7.2f s  CR=%6.2f  domain blocks=%d" %
                  (i + 1, tlabel(t), p, tm, cr, len(e.dom)), flush=True)
    head = ["Sample MRI Image"] + [tlabel(t) for t in TAU_LIST]
    blocks, mds = [], []
    for key, title in (("psnr", "Table 1  PSNR at Different Levels of Compression (dB)"),
                       ("time", "Table 2  Time Taken at Different Levels of Compression (sec)"),
                       ("cr", "Table 3  Compression Ratio at Different Thresholds")):
        rows = [[str(i + 1)] + ["%.2f" % enc[(i, t)].metrics[key] for t in TAU_LIST] for i in range(len(images))]
        rows.append(["Avg"] + ["%.2f" % np.mean([enc[(i, t)].metrics[key] for i in range(len(images))]) for t in TAU_LIST])
        blocks.append(box(title, head, rows)); mds.append(md(title, head, rows))

    # ---- Table 4: the three algorithms on Sample image 4, tau = 1e-5
    t4 = {}
    for algo in ("standard", "alg1", "alg2"):
        e, rec, p, tm, cr = run(images[t4_idx], algo, 1e-5, a.rule, a.repeats)
        t4[algo] = (p, tm, cr, rec)
        print("  Table 4  %-8s PSNR=%6.2f  time=%8.2f s  CR=%6.2f" % (algo, p, tm, cr), flush=True)
    h4 = ["Metric", "Standard Fractal Encoding", "Proposed Algorithm I (τ=1e-5)", "Proposed Algorithm II (τ=1e-5)"]
    r4 = [["PSNR (dB)"] + ["%.2f" % t4[k][0] for k in ("standard", "alg1", "alg2")],
          ["Compression Time (sec)"] + ["%.2f" % t4[k][1] for k in ("standard", "alg1", "alg2")],
          ["Compression Ratio"] + ["%.2f" % t4[k][2] for k in ("standard", "alg1", "alg2")]]
    ttl4 = "Table 4  PSNR achieved for Different Algorithms (Sample MRI Image %d)" % (t4_idx + 1)
    blocks.append(box(ttl4, h4, r4)); mds.append(md(ttl4, h4, r4))

    text = "\n".join(mapping) + "\n\n" + "\n".join(settings) + "\n\n" + "\n\n".join(blocks)
    print("\n" + text)
    open(os.path.join(a.out, "tables.txt"), "w", encoding="utf-8").write(text + "\n")
    open(os.path.join(a.out, "tables.md"), "w", encoding="utf-8").write(
        "```\n" + "\n".join(mapping + [""] + settings) + "\n```\n\n" + "\n".join(mds))
    make_figures(a.out, images, enc, t4, t4_idx)
    print("\nSaved in:", os.path.abspath(a.out))


if __name__ == "__main__":
    main()
